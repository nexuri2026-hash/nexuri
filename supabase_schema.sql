-- 1. TABLA PROFILES (Vinculada a auth.users)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  nombre TEXT NOT NULL DEFAULT 'Usuario',
  correo TEXT NOT NULL,
  rol TEXT NOT NULL DEFAULT 'administrador' CHECK (rol IN ('administrador', 'supervisor', 'operaria', 'bodega')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Trigger automático: cuando creas un usuario en Authentication -> Users,
-- se crea automáticamente su fila en public.profiles con rol 'administrador' (o el que pase en metadata).
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, nombre, correo, rol)
  VALUES (
    NEW.id,
    COALESCE(NEW.raw_user_meta_data->>'nombre', split_part(NEW.email, '@', 1)),
    NEW.email,
    COALESCE(NEW.raw_user_meta_data->>'rol', 'administrador')
  )
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- Si ya creaste usuarios antes de correr este script, los sincroniza:
INSERT INTO public.profiles (id, nombre, correo, rol)
SELECT
  id,
  COALESCE(raw_user_meta_data->>'nombre', split_part(email, '@', 1)),
  email,
  COALESCE(raw_user_meta_data->>'rol', 'administrador')
FROM auth.users
ON CONFLICT (id) DO NOTHING;


-- 2. TABLA SERVICIOS (Coordinación)
CREATE TABLE IF NOT EXISTS public.servicios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ot TEXT,
  numero_cotizacion TEXT,
  fecha TEXT,
  hora_inicio TEXT,
  hora_termino TEXT,
  categoria TEXT,
  tipo_trabajo TEXT,
  local TEXT,
  direccion TEXT,
  comuna TEXT,
  atm TEXT,
  asignado_a TEXT,
  nombre_solicitante TEXT,
  solicitado_por TEXT,
  banco_empresa TEXT,
  informe TEXT,
  precio_pinares TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- 3. TABLA NOSOTROS
CREATE TABLE IF NOT EXISTS public.nosotros (
  id TEXT PRIMARY KEY,
  data JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- 4. TABLA COTIZACIONES
CREATE TABLE IF NOT EXISTS public.cotizaciones (
  id TEXT PRIMARY KEY,
  data JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- ============================================================================
-- PERMISOS Y POLÍTICAS RLS (Row Level Security)
-- ============================================================================
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.servicios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.nosotros ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cotizaciones ENABLE ROW LEVEL SECURITY;

-- Políticas para usuarios autenticados (acceso completo a las 4 tablas)
DROP POLICY IF EXISTS "Acceso total profiles" ON public.profiles;
CREATE POLICY "Acceso total profiles" ON public.profiles
  FOR ALL TO authenticated, anon USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Acceso total servicios" ON public.servicios;
CREATE POLICY "Acceso total servicios" ON public.servicios
  FOR ALL TO authenticated, anon USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Acceso total nosotros" ON public.nosotros;
CREATE POLICY "Acceso total nosotros" ON public.nosotros
  FOR ALL TO authenticated, anon USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Acceso total cotizaciones" ON public.cotizaciones;
CREATE POLICY "Acceso total cotizaciones" ON public.cotizaciones
  FOR ALL TO authenticated, anon USING (true) WITH CHECK (true);
